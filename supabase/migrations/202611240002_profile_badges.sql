alter table public.profiles
  add column registration_number bigint generated by default as identity;

update public.profiles
   set registration_number = registration_number + (select count(*) from public.profiles);

with ranked_profiles as (
  select id, row_number() over (order by created_at, id) as registration_number
    from public.profiles
)
update public.profiles p
   set registration_number = ranked_profiles.registration_number
  from ranked_profiles
 where ranked_profiles.id = p.id;

select setval(
  pg_get_serial_sequence('public.profiles', 'registration_number'),
  greatest(coalesce((select max(registration_number) from public.profiles), 1), 1),
  exists(select 1 from public.profiles)
);

create unique index profiles_registration_number_unique
  on public.profiles(registration_number);

create table public.user_badges (
  user_id uuid not null references public.profiles(id) on delete cascade,
  badge_code text not null check (badge_code in (
    'first_100', 'super_reviewed',
    'km_100', 'km_500', 'km_1000',
    'safe_5', 'safe_20', 'safe_50'
  )),
  awarded_at timestamptz not null default now(),
  primary key(user_id, badge_code)
);

alter table public.user_badges enable row level security;
create policy "user badges readable" on public.user_badges for select using (true);
grant select on public.user_badges to anon, authenticated;

create or replace function public.refresh_user_badges(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  total_km numeric := 0;
  total_people bigint := 0;
  review_count bigint := 0;
  review_average numeric := 0;
begin
  select coalesce(sum(rides.distance_km), 0)
    into total_km
    from (
      select t.distance_km
        from public.trips t
       where t.driver_id = target_user_id and t.status = 'completed'
      union all
      select t.distance_km
        from public.trips t
        join public.trip_requests r on r.trip_id = t.id
       where r.passenger_id = target_user_id
         and t.type = 'offer' and t.status = 'completed'
         and r.status in ('accepted', 'completed')
      union all
      select t.distance_km
        from public.trips t
        join public.car_invites i on i.trip_id = t.id
       where i.inviter_id = target_user_id
         and i.status = 'accepted' and t.status = 'completed'
    ) rides;

  select coalesce(sum(riders.people), 0)
    into total_people
    from (
      select r.seats as people
        from public.trips t
        join public.trip_requests r on r.trip_id = t.id
       where t.driver_id = target_user_id
         and t.type = 'offer' and t.status = 'completed'
         and r.status in ('accepted', 'completed')
      union all
      select 1 as people
        from public.trips t
        join public.car_invites i on i.trip_id = t.id
       where i.inviter_id = target_user_id
         and i.status = 'accepted' and t.status = 'completed'
    ) riders;

  select count(*), coalesce(avg(r.rating), 0)
    into review_count, review_average
    from public.reviews r
   where r.driver_id = target_user_id;

  insert into public.user_badges(user_id, badge_code)
  select target_user_id, earned.badge_code
    from (values
      ('km_100', total_km >= 100),
      ('km_500', total_km >= 500),
      ('km_1000', total_km >= 1000),
      ('safe_5', total_people >= 5),
      ('safe_20', total_people >= 20),
      ('safe_50', total_people >= 50)
    ) as earned(badge_code, qualifies)
   where earned.qualifies
  on conflict (user_id, badge_code) do nothing;

  if review_count >= 5 and review_average >= 4.8 then
    insert into public.user_badges(user_id, badge_code)
    values (target_user_id, 'super_reviewed')
    on conflict (user_id, badge_code) do nothing;
  else
    delete from public.user_badges
     where user_id = target_user_id and badge_code = 'super_reviewed';
  end if;
end;
$$;

revoke all on function public.refresh_user_badges(uuid) from public, anon, authenticated;

create or replace function public.award_profile_badges()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.registration_number <= 100 then
    insert into public.user_badges(user_id, badge_code)
    values (new.id, 'first_100')
    on conflict (user_id, badge_code) do nothing;
  end if;
  perform public.refresh_user_badges(new.id);
  return new;
end;
$$;

create trigger profiles_award_badges_after_insert
  after insert on public.profiles
  for each row execute function public.award_profile_badges();

create or replace function public.refresh_badges_after_trip_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  affected_user_id uuid;
begin
  perform public.refresh_user_badges(new.driver_id);
  for affected_user_id in
    select r.passenger_id from public.trip_requests r where r.trip_id = new.id
    union
    select i.inviter_id from public.car_invites i where i.trip_id = new.id
    union
    select i.requester_id from public.car_invites i where i.trip_id = new.id
  loop
    perform public.refresh_user_badges(affected_user_id);
  end loop;
  return new;
end;
$$;

create trigger trips_refresh_badges_after_insert
  after insert on public.trips
  for each row execute function public.refresh_badges_after_trip_change();
create trigger trips_refresh_badges_after_update
  after update of status, distance_km on public.trips
  for each row execute function public.refresh_badges_after_trip_change();

create or replace function public.refresh_badges_after_request_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  trip_driver_id uuid;
begin
  select t.driver_id into trip_driver_id from public.trips t where t.id = new.trip_id;
  perform public.refresh_user_badges(new.passenger_id);
  if trip_driver_id is not null then
    perform public.refresh_user_badges(trip_driver_id);
  end if;
  return new;
end;
$$;

create trigger trip_requests_refresh_badges_after_insert
  after insert on public.trip_requests
  for each row execute function public.refresh_badges_after_request_change();
create trigger trip_requests_refresh_badges_after_update
  after update of status, seats on public.trip_requests
  for each row execute function public.refresh_badges_after_request_change();

create or replace function public.refresh_badges_after_invite_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.refresh_user_badges(new.inviter_id);
  perform public.refresh_user_badges(new.requester_id);
  return new;
end;
$$;

create trigger car_invites_refresh_badges_after_insert
  after insert on public.car_invites
  for each row execute function public.refresh_badges_after_invite_change();
create trigger car_invites_refresh_badges_after_update
  after update of status on public.car_invites
  for each row execute function public.refresh_badges_after_invite_change();

create or replace function public.refresh_badges_after_review_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op <> 'INSERT' then
    perform public.refresh_user_badges(old.driver_id);
  end if;
  if tg_op <> 'DELETE' then
    perform public.refresh_user_badges(new.driver_id);
  end if;
  return null;
end;
$$;

create trigger reviews_refresh_badges_after_change
  after insert or update or delete on public.reviews
  for each row execute function public.refresh_badges_after_review_change();

insert into public.user_badges(user_id, badge_code)
select id, 'first_100' from public.profiles where registration_number <= 100
on conflict (user_id, badge_code) do nothing;

do $$
declare
  profile_id uuid;
begin
  for profile_id in select id from public.profiles loop
    perform public.refresh_user_badges(profile_id);
  end loop;
end;
$$;